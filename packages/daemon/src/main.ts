#!/usr/bin/env node
/**
 * The kanbot daemon: a thin loop — watch, claim, worktree, run playbook, stream, hand off.
 * It runs on the user's machine, next to the user's code. The board coordinates; this moves.
 */
import { parseArgs } from "node:util";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import type { BoardSnapshot, Card, Lane, Member, Stage } from "@kanbot/shared";
import { LANE_DEVELOPING, LANE_AGENT_REVIEW, REVIEW_CYCLE_BUDGET, STAGE_HANDOFF } from "@kanbot/shared";
import { BoardClient, laneByName } from "./api.js";
import {
  continueBranchWorktree,
  createPullRequest,
  createReviewWorktree,
  createWorktree,
  currentBranch,
  git,
  hasCommits,
  isDirty,
  originUrl,
  pushBranch,
  removeWorktree,
  tryGit,
  type Worktree,
} from "./git.js";
import {
  playbookFor,
  REVIEW_OUTPUT_FILE,
  SPEC_OUTPUT_FILE,
  VERDICT_APPROVED,
  VERDICT_CHANGES,
} from "./playbooks.js";
import { Progress, runClaude, type RunResult } from "./run.js";

const CLAIM_TTL_SEC = 120;
const HEARTBEAT_MS = 30_000;
const POLL_MS = 2000;

const sleep = (ms: number): Promise<void> => new Promise((r) => setTimeout(r, ms));

/* -------------------------------------------------------------------- args */

const { values } = parseArgs({
  options: {
    board: { type: "string", default: "http://localhost:4777" },
    repo: { type: "string" },
    name: { type: "string" },
    "dry-run": { type: "boolean", default: false },
    model: { type: "string" },
    "permission-mode": { type: "string" },
    help: { type: "boolean", default: false, short: "h" },
  },
  allowPositionals: false,
});

const USAGE = `kanbot daemon

  tsx src/main.ts --repo <path> --name <agentName> [options]

  --board <url>              board base URL (default http://localhost:4777)
  --repo <path>              git repository to work in (required)
  --name <agentName>         name to join the board under (required)
  --dry-run                  fake the coding agent; exercise every other path for real
  --model <model>            passed through to \`claude --model\`
  --permission-mode <mode>   passed through to \`claude --permission-mode\`
  -h, --help
`;

if (values.help || !values.repo || !values.name) {
  console.log(USAGE);
  process.exit(values.help ? 0 : 1);
}

const repo = resolve(values.repo);
const agentName = values.name;
const dryRun = values["dry-run"] === true;
const client = new BoardClient(values.board ?? "http://localhost:4777");

/* -------------------------------------------------------------------- state */

interface Work {
  card: Card;
  lane: Lane;
  stage: Stage;
}

let me: Member;
let holding: string | null = null;
let active: { worktree: Worktree; stage: Stage } | null = null;
let running = true;

function log(...args: unknown[]): void {
  console.log(`[${new Date().toLocaleTimeString()}]`, ...args);
}

/* ------------------------------------------------------------------ picking */

function isFree(card: Card): boolean {
  if (card.waitingOn) return false; // a human owes this card an answer
  if (!card.claimedBy) return true;
  return card.claimExpiresAt !== null && card.claimExpiresAt <= Date.now();
}

function pick(board: BoardSnapshot): Work | null {
  const stageLanes = board.lanes.filter((l) => l.stage !== null);
  const candidates = board.cards
    .filter((c) => isFree(c) && stageLanes.some((l) => l.id === c.laneId))
    .sort((a, b) => a.createdAt - b.createdAt);

  const card = candidates[0];
  if (!card) return null;
  const lane = stageLanes.find((l) => l.id === card.laneId)!;
  return { card, lane, stage: lane.stage as Stage };
}

/* ---------------------------------------------------------------- dry run */

const CANNED_SPEC = (title: string): string => `# ${title}

## Goal
(dry run) Prove the kanbot pipeline end to end without spawning a coding agent.

## Current behavior
The card sat in a stage lane, unclaimed and unattended.

## Desired behavior
The daemon claims it, opens a worktree, produces this document, hands the card back to
the owner for review, and cleans up after itself.

## Implementation approach
No code was written. This spec was generated by \`--dry-run\`.

## Acceptance criteria
1. The card is claimed by the daemon while the run is in flight.
2. This spec is posted to the card.
3. The card lands in "Spec review" waiting on the owner.

## Tests
None — a dry run writes no code.

## Out of scope
Everything. Re-run without --dry-run to get a real spec.
`;

async function fakeRun(work: Work, worktree: Worktree): Promise<RunResult> {
  const notes = [
    `🛠 reading AGENTS.md and looking around ${repo}`,
    `🛠 working in ${worktree.branch}`,
    `🛠 wrapping up the ${work.stage} stage (dry run — no coding agent was spawned)`,
  ];
  for (const note of notes) {
    await sleep(1000);
    await client.comment(work.card.id, note, me.id).catch(() => undefined);
  }

  if (work.stage === "spec") {
    await writeFile(join(worktree.path, SPEC_OUTPUT_FILE), CANNED_SPEC(work.card.title), "utf8");
  } else if (work.stage === "review") {
    await writeFile(
      join(worktree.path, REVIEW_OUTPUT_FILE),
      `(dry run) No real review was performed; no coding agent was spawned.\n\n${VERDICT_APPROVED}\n`,
      "utf8",
    );
  } else {
    await git(worktree.path, ["commit", "--allow-empty", "-m", "kanbot dry-run"]);
  }
  return { code: 0 };
}

/* ------------------------------------------------------------------ working */

async function workOn(work: Work, lanes: Lane[]): Promise<void> {
  const { card, stage } = work;

  try {
    await client.claim(card.id, me.id, CLAIM_TTL_SEC);
  } catch (err) {
    log(`skipped "${card.title}": ${(err as Error).message}`);
    return;
  }
  holding = card.id;

  const beat = setInterval(() => {
    void client.heartbeat(card.id, me.id, CLAIM_TTL_SEC).catch(() => undefined);
  }, HEARTBEAT_MS);
  beat.unref();

  let worktree: Worktree | null = null;
  const progress = new Progress((text) => client.comment(card.id, text, me.id).then(() => undefined));

  try {
    const detail = await client.card(card.id);
    const existingBranch = detail.card.refs.branch;
    const baseRef = (await currentBranch(repo)) ?? "master";

    if (stage === "review") {
      if (!existingBranch) throw new Error("card has no branch to review");
      worktree = await createReviewWorktree(repo, card.title, existingBranch);
    } else if (stage === "develop" && existingBranch) {
      // A bounced card continues its branch; fixes stack on top of the reviewed commits.
      worktree = await continueBranchWorktree(repo, card.title, existingBranch);
    } else {
      worktree = await createWorktree(repo, card.title);
    }
    active = { worktree, stage };
    log(`claimed "${card.title}" → ${worktree.branch}`);
    await client.comment(
      card.id,
      `Starting the ${stage} stage in \`${worktree.branch}\`${dryRun ? " (dry run)" : ""}.`,
      me.id,
    );

    // The card is the spec while it is drafted; development commits it to the repo.
    let specPath: string | undefined;
    if (stage === "develop") {
      const spec = detail.card.spec;
      if (!spec || !spec.trim()) {
        throw new Error("card has no spec; it cannot be developed yet");
      }
      specPath = join("docs", "specs", `${worktree.slug}.md`);
      const abs = join(worktree.path, specPath);
      if (!existsSync(abs)) {
        await mkdir(dirname(abs), { recursive: true });
        await writeFile(abs, spec.endsWith("\n") ? spec : `${spec}\n`, "utf8");
      }
    }

    const prompt = playbookFor(stage, {
      title: card.title,
      body: card.body,
      specPath,
      branch: worktree.branch,
      baseRef,
    });

    progress.start();
    const result = dryRun
      ? await fakeRun(work, worktree)
      : await runClaude({
          cwd: worktree.path,
          prompt,
          model: values.model,
          permissionMode: values["permission-mode"],
          onText: (text) => progress.push(text),
          onLog: (line) => console.error(line),
        });
    await progress.stop();

    if (result.code !== 0) {
      throw new Error(`the coding agent exited ${result.code}${result.error ? `: ${result.error}` : ""}`);
    }

    await handOff(work, worktree, lanes, baseRef);
  } catch (err) {
    await progress.stop().catch(() => undefined);
    const reason = err instanceof Error ? err.message : String(err);
    log(`failed "${card.title}": ${reason}`);
    // The card stays in its lane; the owner decides what happens next.
    await client
      .comment(card.id, `⚠️ Run failed: ${reason.slice(0, 900)}`, me.id)
      .catch(() => undefined);
    await client
      .attention(card.id, `run failed: ${reason.slice(0, 200)}`, me.id)
      .catch(() => undefined);
    await client.release(card.id, me.id, `run failed: ${reason.slice(0, 160)}`).catch(() => undefined);
  } finally {
    clearInterval(beat);
    holding = null;
    active = null;
    if (worktree) {
      await removeWorktree(repo, worktree, stage === "spec").catch(() => undefined);
    }
  }
}

function prBody(card: Card, review: string): string {
  return `## Summary
${card.body.trim() || card.title}

## Specification
Committed on this branch under \`docs/specs/\`; drafted and approved on the kanbot board.

## Agent review
${review.slice(0, 2500)}

---
🤖 Opened by kanbot after an independent agent review. A human merges.`;
}

/**
 * Hand the card onward. Spec review, Agent review, and PR review are not human-only lanes,
 * so an agent may move a card into them; Ready and Done are.
 */
async function handOff(
  work: Work,
  worktree: Worktree,
  lanes: Lane[],
  baseRef: string,
): Promise<void> {
  const { card, stage } = work;
  const target = laneByName(lanes, STAGE_HANDOFF[stage]);

  if (stage === "spec") {
    const specFile = join(worktree.path, SPEC_OUTPUT_FILE);
    if (!existsSync(specFile)) {
      throw new Error(`the run produced no ${SPEC_OUTPUT_FILE}`);
    }
    const markdown = await readFile(specFile, "utf8");
    if (!markdown.trim()) throw new Error(`${SPEC_OUTPUT_FILE} is empty`);
    await client.postSpec(card.id, markdown, me.id);
    await client.move(card.id, target.id, me.id);
    await client.attention(card.id, "spec ready for review", me.id);
    await client.release(card.id, me.id, "spec stage complete");
    log(`handed "${card.title}" to the owner in ${target.name}`);
    return;
  }

  if (stage === "develop") {
    // Never declare success on an empty branch or uncommitted work — verify the deliverable.
    const commits = Number((await tryGit(worktree.path, ["rev-list", `${baseRef}..HEAD`, "--count"])) ?? "0");
    if (commits === 0) {
      throw new Error(`the run produced no commits on ${worktree.branch}`);
    }
    if (await isDirty(worktree.path)) {
      throw new Error(
        `the run left uncommitted changes in the worktree at ${worktree.path}; not handing off`,
      );
    }
    const head = (await tryGit(worktree.path, ["rev-parse", "--short", "HEAD"])) ?? "";
    await client.setRefs(card.id, { branch: worktree.branch }, me.id);
    await client.move(card.id, target.id, me.id);
    await client.comment(
      card.id,
      `Branch ready: \`${worktree.branch}\`${head ? ` @ ${head}` : ""} — queued for agent review.`,
      me.id,
    );
    await client.release(card.id, me.id, "develop stage complete");
    log(`queued "${card.title}" for agent review`);
    return;
  }

  // review
  const reviewFile = join(worktree.path, REVIEW_OUTPUT_FILE);
  if (!existsSync(reviewFile)) {
    throw new Error(`the run produced no ${REVIEW_OUTPUT_FILE}`);
  }
  const review = (await readFile(reviewFile, "utf8")).trim();
  const lastLine = review.split("\n").filter((l) => l.trim()).pop()?.trim() ?? "";
  if (lastLine !== VERDICT_APPROVED && lastLine !== VERDICT_CHANGES) {
    throw new Error(`review ended without a clear verdict (last line: "${lastLine.slice(0, 60)}")`);
  }
  await client.comment(
    card.id,
    `🔎 Agent review of \`${worktree.branch}\`:\n\n${review.slice(0, 3800)}`,
    me.id,
  );

  if (lastLine === VERDICT_APPROVED) {
    // The PR review lane's real form: an actual GitHub PR, opened on approval.
    let prUrl = card.refs.prUrl;
    if (!dryRun && (await originUrl(repo))) {
      try {
        await pushBranch(repo, worktree.branch);
        if (!prUrl) {
          prUrl = await createPullRequest(
            repo,
            worktree.branch,
            card.title,
            prBody(card, review),
          );
        }
        await client.setRefs(card.id, { branch: worktree.branch, prUrl }, me.id);
      } catch (err) {
        prUrl = card.refs.prUrl; // don't advertise a PR we failed to make
        await client.comment(
          card.id,
          `⚠️ Could not open a GitHub PR: ${(err as Error).message.slice(0, 300)} — the branch is still available locally.`,
          me.id,
        );
      }
    }
    await client.move(card.id, target.id, me.id);
    await client.attention(
      card.id,
      prUrl
        ? `PR ready for your review: ${prUrl}`
        : `agent-reviewed and approved: ${worktree.branch}`,
      me.id,
    );
    await client.release(card.id, me.id, "review stage complete: approved");
    log(`approved "${card.title}" → ${target.name}${prUrl ? ` (${prUrl})` : ""}`);
    return;
  }

  // CHANGES REQUESTED: bounce back to Developing — bounded, then escalate to the owner.
  const detail = await client.card(card.id);
  const bounces = detail.activity.filter(
    (a) =>
      a.type === "card_moved" &&
      a.data.from === LANE_AGENT_REVIEW &&
      a.data.to === LANE_DEVELOPING,
  ).length;
  if (bounces + 1 >= REVIEW_CYCLE_BUDGET) {
    await client.attention(
      card.id,
      `agent review requested changes ${bounces + 1} times — needs your call`,
      me.id,
    );
    await client.release(card.id, me.id, "review cycle budget exhausted");
    log(`escalated "${card.title}" to the owner after ${bounces + 1} review cycles`);
    return;
  }
  const developing = laneByName(lanes, LANE_DEVELOPING);
  await client.move(card.id, developing.id, me.id);
  await client.release(card.id, me.id, "review stage complete: changes requested");
  log(`bounced "${card.title}" back to ${developing.name} (cycle ${bounces + 1})`);
}

/* --------------------------------------------------------------------- run */

async function tick(): Promise<void> {
  const board = await client.board();
  const work = pick(board);
  if (!work) return;
  await workOn(work, board.lanes);
}

async function main(): Promise<void> {
  if (!existsSync(join(repo, ".git"))) {
    console.error(`not a git repository: ${repo}`);
    process.exit(1);
  }
  if (!(await hasCommits(repo))) {
    console.error(`${repo} has no commits; git worktree needs at least one`);
    process.exit(1);
  }

  me = await client.join(agentName);
  log(`joined ${values.board} as ${me.name} (${me.id})${dryRun ? " [dry run]" : ""}`);
  log(`repo: ${repo}`);

  while (running) {
    try {
      await tick();
    } catch (err) {
      log(`poll failed: ${(err as Error).message}`);
    }
    if (running) await sleep(POLL_MS);
  }
}

let shuttingDown = false;
async function shutdown(): Promise<void> {
  if (shuttingDown) process.exit(1);
  shuttingDown = true;
  running = false;
  console.log("\nSIGINT — releasing claim");
  if (holding && me) {
    await client.release(holding, me.id, "daemon shut down").catch(() => undefined);
  }
  // Don't leave a half-finished worktree behind for the next run to trip over.
  if (active) {
    await removeWorktree(repo, active.worktree, active.stage === "spec").catch(() => undefined);
  }
  process.exit(0);
}

process.on("SIGINT", () => void shutdown());
process.on("SIGTERM", () => void shutdown());

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
